/**
 * Every city page on the site: North American markets we staff directly, plus
 * international markets served through partner fabrication. The international
 * set exists because ~60 legacy beaumontandco.ca city URLs pointed at these
 * markets — each one now 301s to a real, topically matching page.
 */
export const CITIES: City[] = [...NORTH_AMERICAN_CITIES, ...INTERNATIONAL_CITIES];

/** Human label for a city, e.g. "Orlando, FL" or "Barcelona, Spain". */
export const cityLabel = (c: City) =>
  `${c.city}, ${c.international ? c.countryName : c.stateAbbr}`;

export const CITY_URL_SUFFIX = "-trade-show-booth-rentals";
/** Keyword-rich public URL slug, e.g. "orlando-trade-show-booth-rentals". */
export const cityUrlSlug = (slug: string) => `${slug}${CITY_URL_SUFFIX}`;
/** Resolves both the canonical SEO slug and the legacy short slug. */
export const getCity = (slug: string) => {
  const alias = CITY_ALIASES[slug.replace(CITY_URL_SUFFIX, "")];
  const target = alias ?? slug;
  return CITIES.find((c) => cityUrlSlug(c.slug) === target || c.slug === target);
};

/** Removed city pages that 301 to the nearest live city page. */
const CITY_ALIASES: Record<string, string> = {
  louiseville: "montreal",
  "san-pedro-garza-garcia": "monterrey",
};


/** Curated footer list — the full set is cross-linked from every city page. */
